import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { discoverEnvironment } from '../dist/discovery.js';
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'onemcp-discovery-'));
let passed = 0;
const check = (value, note) => { assert.ok(value, note); passed++; };
try {
  const dir = path.join(root, '.config/tunnel-client'); await fs.mkdir(dir, { recursive: true });
  const secret = 'sk-test-do-not-return-credential';
  await fs.writeFile(path.join(dir, 'demo.yaml'), `config_version: 1\ncontrol_plane:\n  tunnel_id: tunnel_demo123\n  api_key: ${secret}\nmcp:\n  server_url: http://127.0.0.1:8787/mcp?token=${secret}\n`);
  const base = { home: root, env: { PATH: '' }, platform: 'test' };
  let data = await discoverEnvironment(base);
  check(data.tunnel.directorySource === 'home-default', 'default directory');
  check(data.profiles[0].tunnelID === 'tunnel_demo123', 'whitelisted tunnel ID');
  check(data.profiles[0].endpoint === 'http://127.0.0.1:8787', 'URL only emits origin');
  check(!JSON.stringify(data).includes(secret), 'no secret output');
  check(data.readOnly && data.schemaVersion === 1, 'stable schema');
  const custom = path.join(root, 'custom'); await fs.mkdir(custom);
  data = await discoverEnvironment({ ...base, env: { XDG_CONFIG_HOME: '/nonexistent-test-dir', TUNNEL_CLIENT_PROFILE_DIR: custom, TUNNEL_CLIENT_PROFILE: 'demo' } });
  check(data.tunnel.profileDirectory === custom, 'profile env precedes XDG');
  check(data.warnings.some(w => w.includes('Selected named')), 'missing selection explained');
  data = await discoverEnvironment({ ...base, env: { XDG_CONFIG_HOME: root } });
  check(data.tunnel.profileDirectory === path.join(root, 'tunnel-client'), 'XDG precedence');
  await fs.symlink('demo.yaml', path.join(dir, 'alias.yaml'));
  await fs.writeFile(path.join(root, 'outside.yaml'), `control_plane:\n  tunnel_id: tunnel_outside\n`);
  await fs.symlink('../../outside.yaml', path.join(dir, 'escape.yaml'));
  await fs.symlink(path.join(dir, 'demo.yaml'), path.join(dir, 'absolute.yaml'));
  await fs.writeFile(path.join(dir, 'large.yaml'), ' '.repeat(131073));
  data = await discoverEnvironment({ ...base, env: { TUNNEL_CLIENT_PROFILE: 'demo' } });
  check(data.tunnel.profiles.find(p => p.name === 'alias.yaml').status === 'inspected', 'internal relative symlink supported');
  check(data.tunnel.profiles.find(p => p.name === 'escape.yaml').status === 'skipped', 'escape rejected');
  check(data.tunnel.profiles.find(p => p.name === 'absolute.yaml').status === 'skipped', 'absolute named symlink rejected');
  check(data.tunnel.profiles.find(p => p.name === 'large.yaml').status === 'skipped', 'oversized rejected');
  check(data.tunnel.profiles.find(p => p.name === 'demo.yaml').selected, 'named selection');
  const linkedDir = path.join(root, 'linked'); await fs.symlink(dir, linkedDir);
  data = await discoverEnvironment({ ...base, env: { TUNNEL_CLIENT_PROFILE_DIR: linkedDir } });
  check(data.profiles.some(p => p.name === 'demo'), 'directory symlink supported');
  data = await discoverEnvironment({ ...base, env: { TUNNEL_CLIENT_PROFILE: 'demo', TUNNEL_CLIENT_CONFIG: path.join(dir, 'demo.yaml') } });
  check(data.tunnel.selectionSource === null && data.warnings.some(w => w.includes('Conflicting')), 'conflict not silently resolved');
  check(data.tunnel.configFiles.length === 1, 'explicit config inspected');
  await fs.writeFile(path.join(dir, 'complex.yaml'), 'control_plane:\n  tunnel_id: &anchor tunnel_fake\nmcp:\n  command: [sh, -c, secret]\n');
  data = await discoverEnvironment(base);
  check(!data.profiles.find(p => p.name === 'complex').tunnelID, 'complex YAML not misrepresented');
  const binaryDir = path.join(root, 'bin'); await fs.mkdir(binaryDir);
  await fs.writeFile(path.join(binaryDir, 'node'), '#!/bin/sh\nexit 0\n', { mode: 0o700 });
  const executable = path.join(binaryDir, 'tunnel-client'); await fs.writeFile(executable, '#!/bin/sh\ntouch SHOULD_NEVER_EXECUTE\n', { mode: 0o700 });
  data = await discoverEnvironment({ ...base, env: { PATH: binaryDir } });
  check(data.clients.some(c => c.path === executable && c.version === undefined), 'binary candidate no invented version');
  check(data.clients.every(c => c.id.startsWith('tunnel-client:')) && data.binaries.some(c => c.name === 'node' && c.available), 'GUI facade excludes Node while detailed binaries retain it');
  check(!(await fs.readdir(root)).includes('SHOULD_NEVER_EXECUTE'), 'no binary executed');
  for (let i = 0; i < 70; i++) await fs.writeFile(path.join(dir, `p${i}.yaml`), 'config_version: 1');
  data = await discoverEnvironment(base);
  check(data.tunnel.profiles.length <= 64 && data.warnings.some(w => /truncated/.test(w)), 'bounded profiles');
  console.log(`Discovery: ${passed} assertions passed.`);
} finally { await fs.rm(root, { recursive: true, force: true }); }
